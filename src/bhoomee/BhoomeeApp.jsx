/* canvas card composer */
function loadImg(src) { return new Promise((res, rej) => { const i = new Image(); i.crossOrigin = "anonymous"; i.onload = () => res(i); i.onerror = rej; i.src = src; }); }
function wrap(ctx, text, x, y, maxW, lh) {
  const words = (text || "").split(" ");
  let line = "", yy = y;
  for (const w of words) {
    const test = line ? line + " " + w : w;
    if (ctx.measureText(test).width > maxW && line) { ctx.fillText(line, x, yy); line = w; yy += lh; } else line = test;
  }
  if (line) ctx.fillText(line, x, yy);
  return yy;
}
async function composeCard(off) {
  const W = 1080, H = 1350, cv = document.createElement("canvas"); cv.width = W; cv.height = H;
  const ctx = cv.getContext("2d");
  try { if (document.fonts && document.fonts.ready) await document.fonts.ready; } catch (e) { /* ignore */ }
  const k = off.sky || "day";
  const graded = k === "night" ? "#2a3350" : k === "wet" ? "#5f7371" : (k === "dawn" || k === "evening") ? "#c98f4e" : "#6f9193";
  const photoH = 860;
  ctx.fillStyle = graded; ctx.fillRect(0, 0, W, photoH);
  if (off.photo) {
    try { const img = await loadImg(off.photo); const s = Math.max(W / img.width, photoH / img.height); const dw = img.width * s, dh = img.height * s; ctx.drawImage(img, (W - dw) / 2, (photoH - dh) / 2, dw, dh); } catch (e) { /* keep bg */ }
  }
  const g = ctx.createLinearGradient(0, photoH - 260, 0, photoH); g.addColorStop(0, "rgba(0,0,0,0)"); g.addColorStop(1, "rgba(0,0,0,0.3)"); ctx.fillStyle = g; ctx.fillRect(0, photoH - 260, W, 260);
  ctx.fillStyle = "#faf5ea"; ctx.fillRect(0, photoH, W, H - photoH);
  ctx.fillStyle = "#2a1c0a"; ctx.textBaseline = "top"; ctx.font = "300 52px 'Fraunces', Georgia, serif";
  const y = wrap(ctx, receiveLine(), 70, photoH + 46, W - 140, 62);
  if (off.word) { ctx.font = "italic 300 40px 'Fraunces', Georgia, serif"; ctx.fillStyle = off.tint || "#6E7A4F"; ctx.fillText("- " + off.word, 70, y + 74); }
  ctx.font = "500 24px 'Inter', system-ui, sans-serif"; ctx.fillStyle = "#8a5a2a"; ctx.fillText((off.domain || "").toUpperCase() + "  " + (off.arc || "").toUpperCase(), 70, H - 120);
  ctx.font = "400 24px 'Inter', system-ui, sans-serif"; ctx.fillStyle = "#a89a80"; ctx.fillText((off.place || "") + " - " + fmtDate(off.date), 70, H - 82);
  ctx.font = "italic 300 30px 'Fraunces', Georgia, serif"; ctx.fillStyle = "#c2b393"; ctx.textAlign = "right"; ctx.fillText("bhoomee", W - 60, H - 96); ctx.textAlign = "left";
  return await new Promise((res) => cv.toBlob((b) => res(b), "image/png", 0.92));
}

