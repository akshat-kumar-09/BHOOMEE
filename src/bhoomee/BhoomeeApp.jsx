function Seal({ filled, of, size = 64, stroke = "#6f8b87" }) {
  const total = Math.max(1, of); const frac = Math.min(1, filled / total);
  const r = size / 2 - 3, cx = size / 2, cy = size / 2, circ = 2 * Math.PI * r;
  return (
    <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`}>
      <circle cx={cx} cy={cy} r={r} fill="none" stroke={stroke} strokeWidth="4" opacity="0.5" />
      <circle cx={cx} cy={cy} r={r} fill="none" stroke={C.dawn} strokeWidth="4" strokeLinecap="round" strokeDasharray={`${circ * frac} ${circ}`} transform={`rotate(-90 ${cx} ${cy})`} />
    </svg>
  );
}

