/* One engine, three trip shapes — the mode IS the trip fed to the engine. */
function tripFor(mode, pilgrim, companionWith) {
  if (mode === "Pilgrim") return { days: pilgrim.days, minutesPerDay: pilgrim.minutesPerDay, companion: "solo", hands_free: pilgrim.hands_free };
  if (mode === "Companion") return { days: 1, minutesPerDay: 30, companion: companionWith || "with_one", hands_free: pilgrim.hands_free };
  return { days: 7, minutesPerDay: 20, companion: "solo", hands_free: false }; // Resident: slow, deep, local, ongoing
}

