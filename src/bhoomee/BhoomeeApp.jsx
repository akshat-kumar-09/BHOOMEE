function shorten(s) { if (!s) return ""; const p = s.split(". "); return p.length > 1 ? p[0] + "." : s; }
function arcStage(m) {
  const map = { notice: "Notice", understand: "Understand", document: "Document", contribute: "Contribute", tend: "Tend", trace: "Understand", measure: "Understand", gather: "Document", offer: "Contribute" };
  if (m && m.arcStage && map[m.arcStage]) return map[m.arcStage];
  if (m && m.id && /^(W3|Wa1|X2)/.test(m.id)) return "Contribute";
  if (m && m.id && /^(W2|N2|L2|Wa2)/.test(m.id)) return "Understand";
  if (m && m.id && /^(S2|A2)/.test(m.id)) return "Document";
  return "Notice";
}
