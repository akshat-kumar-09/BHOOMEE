  function onCapture(e) {
    const file = e.target.files && e.target.files[0]; if (!file) return;
    const reader = new FileReader();
    reader.onload = () => { setCapturePhoto(reader.result); setView("offering"); };
    reader.readAsDataURL(file);
  }
