function skyKeyOf(senses) {
  const p = (senses?.daylight_phase || "").toLowerCase();
  const wet = !!senses?.wet_now || /wet|rain|monsoon|snow|drizzle/.test((senses?.weather || "").toLowerCase());
  if (/night|dark/.test(p)) return "night";
  if (wet) return "wet";
  if (/dawn|sunrise/.test(p)) return "dawn";
  if (/evening|dusk|low|golden/.test(p)) return "evening";
  return "day";
}
const skyByKey = (k) => SKY[k] || SKY.day;

